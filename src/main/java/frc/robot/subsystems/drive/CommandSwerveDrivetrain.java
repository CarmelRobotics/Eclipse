    // === Active self-test (pit motor test) ===
    // Rotates all four modules in place (steer test), then briefly drives forward (drive
    // test -- THE ROBOT MOVES; keep it on blocks or with a clear runway). Verifies each
    // module's steer angle reaches the commanded direction and each drive wheel actually
    // turns. Only meaningful while enabled; SystemsCheck guards that. Publishes pass/fail
    // per module under SystemsCheck/Drive/*.
    public Command selfTestCommand() {
        final SwerveRequest.PointWheelsAt point = new SwerveRequest.PointWheelsAt();
        final SwerveRequest.RobotCentric roll = new SwerveRequest.RobotCentric()
            .withDriveRequestType(DriveRequestType.OpenLoopVoltage);
        final SwerveRequest.SwerveDriveBrake brake = new SwerveRequest.SwerveDriveBrake();
        return Commands.sequence(
            runOnce(() -> SmartDashboard.putString("SystemsCheck/Drive/Status",
                "steer test - wheels rotating in place")),
            applyRequest(() -> point.withModuleDirection(Rotation2d.fromDegrees(90))).withTimeout(0.9),
            runOnce(() -> checkSteerReached(90.0)),
            applyRequest(() -> point.withModuleDirection(Rotation2d.kZero)).withTimeout(0.6),
            runOnce(() -> SmartDashboard.putString("SystemsCheck/Drive/Status",
                "DRIVE test - ROBOT WILL MOVE")),
            applyRequest(() -> roll.withVelocityX(0.4).withVelocityY(0.0).withRotationalRate(0.0)).withTimeout(0.5),
            runOnce(this::checkDriveMoving),
            applyRequest(() -> brake).withTimeout(0.4),
            runOnce(() -> {
                boolean pass = true;
                for (String corner : kSelfTestCorners) {
                    pass = pass
                        && SmartDashboard.getBoolean("SystemsCheck/Drive/" + corner + "/Steer", false)
                        && SmartDashboard.getBoolean("SystemsCheck/Drive/" + corner + "/Drive", false);
                }
                SmartDashboard.putBoolean("SystemsCheck/Drive/Pass", pass);
                SmartDashboard.putString("SystemsCheck/Drive/Status", pass ? "PASS" : "FAIL");
            })
        ).finallyDo(() -> setControl(new SwerveRequest.Idle()));
    }

    private static final String[] kSelfTestCorners = {"FrontLeft", "FrontRight", "BackLeft", "BackRight"};

    // Each module's steer angle is within tolerance of the commanded direction, folded to
    // ±90: steer optimization may legally point a module 180 degrees opposite (with drive
    // reversed) whenever that's the shorter rotation -- e.g. wheels left at X-lock's ±45
    // flip when commanded to 90. Both orientations are a working steer motor, so the error
    // is computed modulo 180 and a reversed module passes.
    private void checkSteerReached(double targetDeg) {
        for (int i = 0; i < kSelfTestCorners.length; i++) {
            double angleDeg = getModule(i).getCurrentState().angle.getDegrees();
            double errDeg = Math.abs(MathUtil.inputModulus(angleDeg - targetDeg, -90.0, 90.0));
            SmartDashboard.putBoolean("SystemsCheck/Drive/" + kSelfTestCorners[i] + "/Steer", errDeg < 10.0);
        }
    }

    // Each module's drive wheel is actually turning.
    private void checkDriveMoving() {
        for (int i = 0; i < kSelfTestCorners.length; i++) {
            double speed = Math.abs(getModule(i).getCurrentState().speedMetersPerSecond);
            SmartDashboard.putBoolean("SystemsCheck/Drive/" + kSelfTestCorners[i] + "/Drive", speed > 0.1);
        }
    }

    public ChassisSpeeds getFieldRelativeSpeeds() {
        return ChassisSpeeds.fromRobotRelativeSpeeds(getState().Speeds, getState().Pose.getRotation());
    }

    // === Shoot-on-the-move solution ===
    // shotVector = (hub - robot) - robotVelocity * lead * TOF: the displacement the ball
    // must cover in the robot's frame so it lands on the hub even though the robot is
    // moving. Solved ONCE per loop in updateShotSolution(); the getters below return the
    // cached solution. It used to be re-derived 5-6 times per loop straight from raw
    // module-state speeds, which is where the on-the-move twitchiness came from:
    //   - raw swerve speeds are noisy, and every wiggle went straight into the aim target
    //     the heading controller was chasing at P=8
    //   - TOF was looked up at the RAW hub distance while the table lookup used the led
    //     distance, so the lead itself was computed with the wrong flight time
    private void updateShotSolution() {
        Translation2d robotToHub = getHubPosition().minus(getState().Pose.getTranslation());

        // Low-pass the field velocity used for lead (~0.15 s time constant): the aim
        // target follows real acceleration but stops chattering with module noise.
        ChassisSpeeds speeds = getFieldRelativeSpeeds();
        Translation2d filteredVelocity = new Translation2d(
            m_shotVelFilterX.calculate(speeds.vxMetersPerSecond),
            m_shotVelFilterY.calculate(speeds.vyMetersPerSecond));

        Translation2d acceleration = filteredVelocity.minus(m_filteredFieldVelocity).times(50.0);
        m_filteredFieldVelocity = filteredVelocity;
        // The Pigeon is the impact detector: a collision has a sharp change in
        // acceleration (jerk), unlike a normal deliberate driver acceleration.
        Translation2d pigeonAcceleration = new Translation2d(
            m_pigeonAccelFilterX.calculate(getPigeon2().getAccelerationX().getValueAsDouble()),
            m_pigeonAccelFilterY.calculate(getPigeon2().getAccelerationY().getValueAsDouble()));
        Translation2d jerk = pigeonAcceleration.minus(m_previousPigeonAcceleration).times(50.0);
        m_previousPigeonAcceleration = pigeonAcceleration;
        m_impactJerk = jerk.getNorm();
        m_impactCooldownRemaining = Math.max(0.0, m_impactCooldownRemaining - 0.02);
        if (FeatureFlags.IMPACT_COMPENSATION.getAsBoolean()
                && m_impactCooldownRemaining <= 0.0
                && m_impactJerk >= m_impactJerkThreshold.get()) {
            m_impactCompensationRemaining = m_impactCompDuration.get();
            m_impactCooldownRemaining = 0.15;
        }
        m_impactCompensationRemaining = Math.max(0.0, m_impactCompensationRemaining - 0.02);
        m_impactAcceleration = FeatureFlags.IMPACT_COMPENSATION.getAsBoolean()
            && m_impactCompensationRemaining > 0.0 ? acceleration : new Translation2d();

        Translation2d lead = filteredVelocity.times(m_moveCompGain.get());
        if (FeatureFlags.IMPACT_COMPENSATION.getAsBoolean()) {
            // The robot's future displacement is v*t + 1/2*a*t^2. This extra term is
            // deliberately short-lived: it catches the velocity change caused by a hit
            // without making normal driver acceleration permanently unstable.
            lead = lead.plus(m_impactAcceleration.times(
                0.5 * m_impactCompGain.get() * m_shotTofSeconds * m_shotTofSeconds));
        }
        // FeatureFlags.ShootOnTheMove off -> zero the lead (aim as if stationary). The
        // filters still run above so they stay warm if it's toggled back on mid-match.
        if (!FeatureFlags.SHOOT_ON_THE_MOVE.getAsBoolean()) {
            lead = new Translation2d();
        }

        // Fixed-point iteration: lead depends on TOF, TOF depends on the led distance.
        // Converges in 2-3 passes at any legal robot speed.
        double tofOffset = SmartDashboard.getNumber(ShooterConstants.kTimeOfFlightOffsetKey, 0);
        double tof = Math.max(0.001, ShooterConstants.getShotTimeOfFlightSeconds(robotToHub.getNorm()) + tofOffset);
        Translation2d shotVector = robotToHub;
        for (int i = 0; i < 3; i++) {
            shotVector = robotToHub.minus(lead.times(tof));
            tof = Math.max(0.001, ShooterConstants.getShotTimeOfFlightSeconds(shotVector.getNorm()) + tofOffset);
        }

        m_shotVector = shotVector;
        m_shotTofSeconds = tof;
        m_shotRadialVelocityMetersPerSecond = speeds.vxMetersPerSecond
            * robotToHub.getX() / Math.max(0.001, robotToHub.getNorm())
            + speeds.vyMetersPerSecond
            * robotToHub.getY() / Math.max(0.001, robotToHub.getNorm());

        // Apply tilt after the horizontal moving-shot solve. The table's nominal pivot
        // angle supplies the calibrated world launch angle; rotating that 3D trajectory
        // through the inverse Pigeon pitch/roll gives both the corrected heading and the
        // pivot correction needed to preserve the same world trajectory.
        m_tiltPivotCorrectionRotations = 0.0;
        if (FeatureFlags.TILT_COMPENSATION.getAsBoolean()) {
            double nominalPivotRotations = ShooterConstants.getScorePivotPosition(
                MathUtil.clamp(shotVector.getNorm(), 0, 6));
            double nominalLaunchAngleDeg = 70.0 - nominalPivotRotations * 360.0;
            double horizontalDistance = Math.max(0.05, shotVector.getNorm());
            double nominalZ = horizontalDistance * Math.tan(Math.toRadians(nominalLaunchAngleDeg));

            Translation2d robotFrameHorizontal = shotVector.rotateBy(
                getState().Pose.getRotation().unaryMinus());
            Translation3d targetVector = new Translation3d(
                robotFrameHorizontal.getX(), robotFrameHorizontal.getY(), nominalZ);
            Rotation3d tilt = new Rotation3d(
                Math.toRadians(getPigeon2().getRoll().getValueAsDouble()),
                Math.toRadians(getPigeon2().getPitch().getValueAsDouble()), 0);
            Translation3d untiltedTarget = targetVector.rotateBy(tilt.unaryMinus());

            m_shotVector = new Translation2d(untiltedTarget.getX(), untiltedTarget.getY())
                .rotateBy(getState().Pose.getRotation());
            double correctedLaunchAngleDeg = Math.toDegrees(Math.atan2(
                untiltedTarget.getZ(), Math.hypot(untiltedTarget.getX(), untiltedTarget.getY())));
            m_tiltPivotCorrectionRotations = -m_tiltPivotGain.get()
                * (correctedLaunchAngleDeg - nominalLaunchAngleDeg) / 360.0;
        }

        // Use the generated 2D map after tilt has finalized the effective shot distance.
        // If the map is missing or does not cover a cell, retain the calibrated 1D fallback.
        var trajectorySolution = FeatureFlags.TRAJECTORY_MAP.getAsBoolean()
            ? frc.robot.subsystems.shooter.TrajectoryMap.lookup(
                m_shotVector.getNorm(), m_shotRadialVelocityMetersPerSecond)
            : java.util.Optional.<frc.robot.subsystems.shooter.TrajectoryMap.Solution>empty();
        if (trajectorySolution.isPresent()) {
            m_shotTofSeconds = trajectorySolution.get().tofSeconds();
            SmartDashboard.putNumber("aim/trajectory robustness margin",
                trajectorySolution.get().robustnessMarginMeters());
        } else {
            m_shotTofSeconds = Math.max(0.001,
                ShooterConstants.getShotTimeOfFlightSeconds(m_shotVector.getNorm()) + tofOffset);
            SmartDashboard.putNumber("aim/trajectory robustness margin", 0.0);
        }

        SmartDashboard.putNumber("aim/pitch deg", getPigeon2().getPitch().getValueAsDouble());
        SmartDashboard.putNumber("aim/roll deg", getPigeon2().getRoll().getValueAsDouble());
        SmartDashboard.putNumber("aim/tilt pivot correction rot", m_tiltPivotCorrectionRotations);
        SmartDashboard.putNumber("aim/impact acceleration", m_impactAcceleration.getNorm());
        SmartDashboard.putNumber("aim/impact jerk", m_impactJerk);
        SmartDashboard.putNumber("aim/impact compensation remaining", m_impactCompensationRemaining);
        SmartDashboard.putNumber("aim/radial velocity", m_shotRadialVelocityMetersPerSecond);
    }

