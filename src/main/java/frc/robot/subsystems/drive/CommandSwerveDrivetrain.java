    // Game data to feed the SHIFTS logic. Real game data always wins. When it's empty:
    //   WITH FMS (real match, data not sent yet): keep it empty -- the compute treats that
    //     as "assume active", which is the safe default when we genuinely don't know the
    //     shift order yet. Never guess on a real field.
    //   WITHOUT FMS: synthesize 'B' so DS *practice mode* actually cycles the shifts --
    //     practice mode supplies a real teleop countdown, and with synthesized data the
    //     active/inactive swaps happen on schedule so drivers can rehearse them. ('B' =
    //     blue inactive first; type R or B into the DS setup tab's Game Data box to choose
    //     the order instead.) Plain teleop without a countdown reads matchTime = -1, which
    //     lands in the always-active window, so ordinary shop driving is unaffected.
    private String effectiveGameData() {
        String gameData = DriverStation.getGameSpecificMessage();
        if (gameData != null && !gameData.isEmpty()) {
            return gameData;
        }
        return DriverStation.isFMSAttached() ? "" : "B";
    }

    private boolean computeOurHubActive(double matchTime, String gameData) {
        return m_localization.alliance()
            .map(alliance -> computeHubActiveForAlliance(alliance, matchTime, gameData))
            .orElse(false);
    }

    /** 2026 game-data hub logic: hubs alternate 25 s active shifts through teleop, with the
     *  order set by the first character of the game data ('R' = red inactive first). */
    private boolean computeHubActiveForAlliance(Alliance alliance, double matchTime, String gameData) {
        if (DriverStation.isAutonomous()) {
            return true;
        }
        if (!DriverStation.isTeleop()) {
            return false;
        }
        // If no game data yet, assume hub active (per WPILib guidance)
        if (gameData == null || gameData.isEmpty()) {
            return true;
        }
        boolean redInactiveFirst;
        switch (gameData.charAt(0)) {
            case 'R' -> redInactiveFirst = true;
            case 'B' -> redInactiveFirst = false;
            default -> {
                return true;
            }
        }

        boolean shift1Active = switch (alliance) {
            case Red -> !redInactiveFirst;
            case Blue -> redInactiveFirst;
        };

        // Teleop timeline (140 s countdown, verified against the WPILib 2026 game-data
        // reference implementation): 140-130 is the 10 s transition with both hubs active,
        // then four 25 s shifts, then both hubs active for the final 30 s (endgame).
        if (matchTime > 130) {
            return true;
        } else if (matchTime > 105) {
            return shift1Active;
        } else if (matchTime > 80) {
            return !shift1Active;
        } else if (matchTime > 55) {
            return shift1Active;
        } else if (matchTime > 30) {
            return !shift1Active;
        } else {
            return true;
        }
    }


