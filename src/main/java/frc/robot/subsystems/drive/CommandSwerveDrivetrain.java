    public double getDistanceToClosestHub() {
        return getState().Pose.getTranslation().getDistance(getHubPosition());
    }

    // Which hub to aim at. In a real match (FMS attached) it's the alliance hub. In the
    // shop it's whichever hub is CLOSER -- practice DSes routinely sit on the wrong
    // alliance, and aiming at the far hub (~9 m away) made the robot "aim forward" from
    // everywhere and clamped the shot tables at max range (max hood angle, max RPS).
    public Translation2d getHubPosition() {
        if (DriverStation.isFMSAttached()) {
            return DriverStation.getAlliance().orElse(Alliance.Blue) == Alliance.Red
                ? ShooterConstants.kRedHubPosition
                : ShooterConstants.kBlueHubPosition;
        }
        Translation2d robot = getState().Pose.getTranslation();
        return robot.getDistance(ShooterConstants.kBlueHubPosition)
                <= robot.getDistance(ShooterConstants.kRedHubPosition)
            ? ShooterConstants.kBlueHubPosition
            : ShooterConstants.kRedHubPosition;
    }

    // === Active self-test (pit motor test) ===
    // Rotates all four modules in place (steer test), then briefly drives forward (drive
    // test -- THE ROBOT MOVES; keep it on blocks or with a clear runway). Verifies each
    // module's steer angle reaches the commanded direction and each drive wheel actually
    // turns. Only meaningful while enabled; SystemsCheck guards that. Publishes pass/fail
    // per module under SystemsCheck/Drive/*.
    public Command selfTestCommand() {
        final SwerveRequest.PointWheelsAt point = new SwerveRequest.PointWheelsAt();
        final SwerveRequest.RobotCentric roll = new SwerveRequest.RobotCentric()
            .withDriveRequestType(DriveRequestType.OpenLoopVoltage);
        final SwerveRequest.SwerveDriveBrake brake = new SwerveRequest.SwerveDriveBrake();
        return Commands.sequence(
            runOnce(() -> SmartDashboard.putString("SystemsCheck/Drive/Status",
                "steer test - wheels rotating in place")),
            applyRequest(() -> point.withModuleDirection(Rotation2d.fromDegrees(90))).withTimeout(0.9),
            runOnce(() -> checkSteerReached(90.0)),
            applyRequest(() -> point.withModuleDirection(Rotation2d.kZero)).withTimeout(0.6),
            runOnce(() -> SmartDashboard.putString("SystemsCheck/Drive/Status",
                "DRIVE test - ROBOT WILL MOVE")),
            applyRequest(() -> roll.withVelocityX(0.4).withVelocityY(0.0).withRotationalRate(0.0)).withTimeout(0.5),
            runOnce(this::checkDriveMoving),
            applyRequest(() -> brake).withTimeout(0.4),
            runOnce(() -> {
                boolean pass = true;
                for (String corner : kSelfTestCorners) {
                    pass = pass
                        && SmartDashboard.getBoolean("SystemsCheck/Drive/" + corner + "/Steer", false)
                        && SmartDashboard.getBoolean("SystemsCheck/Drive/" + corner + "/Drive", false);
                }
                SmartDashboard.putBoolean("SystemsCheck/Drive/Pass", pass);
                SmartDashboard.putString("SystemsCheck/Drive/Status", pass ? "PASS" : "FAIL");
            })
        ).finallyDo(() -> setControl(new SwerveRequest.Idle()));
    }

    private static final String[] kSelfTestCorners = {"FrontLeft", "FrontRight", "BackLeft", "BackRight"};

    // Each module's steer angle is within tolerance of the commanded direction.
    private void checkSteerReached(double targetDeg) {
        for (int i = 0; i < kSelfTestCorners.length; i++) {
            double angleDeg = getModule(i).getCurrentState().angle.getDegrees();
            double errDeg = Math.abs(MathUtil.inputModulus(angleDeg - targetDeg, -180.0, 180.0));
            SmartDashboard.putBoolean("SystemsCheck/Drive/" + kSelfTestCorners[i] + "/Steer", errDeg < 10.0);
        }
    }

    // Each module's drive wheel is actually turning.
    private void checkDriveMoving() {
        for (int i = 0; i < kSelfTestCorners.length; i++) {
            double speed = Math.abs(getModule(i).getCurrentState().speedMetersPerSecond);
            SmartDashboard.putBoolean("SystemsCheck/Drive/" + kSelfTestCorners[i] + "/Drive", speed > 0.1);
        }
    }

    public ChassisSpeeds getFieldRelativeSpeeds() {
        return ChassisSpeeds.fromRobotRelativeSpeeds(getState().Speeds, getState().Pose.getRotation());
    }

    // === Shoot-on-the-move solution ===
    // shotVector = (hub - robot) - robotVelocity * lead * TOF: the displacement the ball
    // must cover in the robot's frame so it lands on the hub even though the robot is
    // moving. Solved ONCE per loop in updateShotSolution(); the getters below return the
    // cached solution. It used to be re-derived 5-6 times per loop straight from raw
    // module-state speeds, which is where the on-the-move twitchiness came from:
    //   - raw swerve speeds are noisy, and every wiggle went straight into the aim target
    //     the heading controller was chasing at P=8
    //   - TOF was looked up at the RAW hub distance while the table lookup used the led
    //     distance, so the lead itself was computed with the wrong flight time
    private void updateShotSolution() {
        Translation2d robotToHub = getHubPosition().minus(getState().Pose.getTranslation());

        // Low-pass the field velocity used for lead (~0.15 s time constant): the aim
        // target follows real acceleration but stops chattering with module noise.
        ChassisSpeeds speeds = getFieldRelativeSpeeds();
        Translation2d lead = new Translation2d(
            m_shotVelFilterX.calculate(speeds.vxMetersPerSecond),
            m_shotVelFilterY.calculate(speeds.vyMetersPerSecond)
        ).times(m_moveCompGain.get());

        // Fixed-point iteration: lead depends on TOF, TOF depends on the led distance.
        // Converges in 2-3 passes at any legal robot speed.
        double tofOffset = SmartDashboard.getNumber(ShooterConstants.kTimeOfFlightOffsetKey, 0);
        double tof = Math.max(0.001, ShooterConstants.getShotTimeOfFlightSeconds(robotToHub.getNorm()) + tofOffset);
        Translation2d shotVector = robotToHub;
        for (int i = 0; i < 3; i++) {
            shotVector = robotToHub.minus(lead.times(tof));
            tof = Math.max(0.001, ShooterConstants.getShotTimeOfFlightSeconds(shotVector.getNorm()) + tofOffset);
        }

        m_shotVector = shotVector;
        m_shotTofSeconds = tof;
    }

    public double getShotTimeOfFlightSeconds() {
        return m_shotTofSeconds;
    }

    public Translation2d getMotionCompensatedShotVector() {
        return m_shotVector;
    }

    // === Compensated hub position (for visualization) ===
    // Where the hub will be in TOF seconds, given current robot motion.
    public Translation2d getCompensatedHubPosition() {
        return getState().Pose.getTranslation().plus(getMotionCompensatedShotVector());
    }

    // === Shot distance ===
    // Magnitude of the compensated shot vector, clamped to the table's valid range (0–6 m).
    public double getShotDistance() {
        return MathUtil.clamp(getMotionCompensatedShotVector().getNorm(), 0, 6);
    }


    // === Shot heading ===
    // Bearing of the motion-compensated shot vector, plus the fixed mechanical offset.
    //
    // NOTE: this used to add an "aim ahead while spinning" term (gyro rate x TOF). It was
    // removed on purpose -- do not add it back into this target. Two reasons:
    //   1. Feedback loop: the heading controller's own rotation fed the term, which pushed
    //      the target further ahead, which sped the rotation up (loop gain ~ P*TOF ~ 6).
    //      The robot oscillated around the hub and could never settle on it.
    //   2. Units: Pigeon getAngularVelocityZWorld() returns degrees/sec and the term used
    //      it as radians, so any rotation at all pinned the target 20 deg off the hub.
    // faceHubCommand drives the spin toward zero before the shot fires, so a spin term has
    // no value in the live aiming target. If spin compensation is ever truly needed, apply
    // it once at ball release, never inside the target the controller is chasing.
    public Rotation2d getHubHeading() {
        return getMotionCompensatedShotVector().getAngle()
            .plus(Rotation2d.fromDegrees(m_headingOffsetDeg.get()));
    }

    // === Heading error ===
    // How far off the robot's current heading is from the computed shot heading.
    // This is the readiness gate for aim (must be within 5°).
    public Rotation2d getHubHeadingError() {
        return Rotation2d.fromRadians(
            MathUtil.angleModulus(getHubHeading().minus(getState().Pose.getRotation()).getRadians())
        );
    }

    // === Face hub command ===
    // Heading-locked drive: the heading snaps to the computed hub heading (with PID stiffness),
    // while the driver retains full translation control. Used during aiming and charging shots.
    public Command faceHubCommand(Supplier<Double> xVelocity, Supplier<Double> yVelocity) {
        return applyRequest(() -> snapRequest
            .withVelocityX(xVelocity.get())
            .withVelocityY(yVelocity.get())
            .withDeadband(Constants.kMaxSpeed * 0.1)
            .withDriveRequestType(DriveRequestType.OpenLoopVoltage)
            .withTargetDirection(getHubHeading())
        );
    }

    // === Passing target ===
    // Ferry landing point: the alliance-zone corner on whichever side of the field the
    // robot is currently on (left side -> left corner, right side -> right corner, with
    // hysteresis at the centerline), inset from the walls so balls land in the zone
    // instead of ricocheting off the corner. Own alliance end comes from the DS setting.
    public Translation2d getPassTarget() {
        boolean red = DriverStation.getAlliance().orElse(Alliance.Blue) == Alliance.Red;
        double inset = m_passCornerInset.get();
        double x = red
            ? ShooterConstants.kFieldLengthMeters - inset
            : inset;
        double y = m_passHighSide
            ? ShooterConstants.kFieldWidthMeters - inset
            : inset;
        return new Translation2d(x, y);
    }

    public double getPassDistance() {
        return getPassTarget().getDistance(getState().Pose.getTranslation());
    }

    // Pass aim is a straight bearing to the landing corner (no motion lead: a pass lands
    // in a zone, not a hub opening). The same mechanical heading trim applies.
    public Rotation2d getPassHeading() {
        return getPassTarget().minus(getState().Pose.getTranslation()).getAngle()
            .plus(Rotation2d.fromDegrees(m_headingOffsetDeg.get()));
    }

    public Rotation2d getPassHeadingError() {
        return Rotation2d.fromRadians(
            MathUtil.angleModulus(getPassHeading().minus(getState().Pose.getRotation()).getRadians())
        );
    }

    // Heading-locked drive toward the pass corner; driver keeps translation control.
    public Command facePassTargetCommand(Supplier<Double> xVelocity, Supplier<Double> yVelocity) {
        return applyRequest(() -> snapRequest
            .withVelocityX(xVelocity.get())
            .withVelocityY(yVelocity.get())
            .withDeadband(Constants.kMaxSpeed * 0.1)
            .withDriveRequestType(DriveRequestType.OpenLoopVoltage)
            .withTargetDirection(getPassHeading())
        );
    }

